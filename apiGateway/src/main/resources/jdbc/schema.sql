-- ==========================================
-- USERS
-- ==========================================

CREATE TABLE IF NOT EXISTS users (
                       user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       name VARCHAR(255) NOT NULL,

                       email VARCHAR(255) NOT NULL UNIQUE,

                       password VARCHAR(255) NOT NULL,

                       enabled BOOLEAN NOT NULL DEFAULT FALSE,

                       email_verified BOOLEAN NOT NULL DEFAULT FALSE,

                       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                       updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                       accept_term_condition VARCHAR(255) NOT NULL,

                       accept_term_condition_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_users_email ON users(email);

-- ==========================================
-- ROLES
-- ==========================================

CREATE TABLE IF NOT EXISTS roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


                       role_name VARCHAR(50) NOT NULL UNIQUE


);

-- ==========================================
-- USER ROLES
-- ==========================================

CREATE TABLE IF NOT EXISTS user_roles (

                            user_id BIGINT NOT NULL,

                            role_name VARCHAR(50) NOT NULL,

                            PRIMARY KEY (user_id, role_name),

                            CONSTRAINT fk_user_roles_user
                                FOREIGN KEY (user_id)
                                REFERENCES users(user_id)
                                ON DELETE CASCADE

);

CREATE INDEX idx_user_roles_user
    ON user_roles(user_id);

CREATE INDEX idx_user_roles_role
    ON user_roles(role_name);

-- ==========================================
-- EMAIL VERIFICATION TOKENS
-- ==========================================

CREATE TABLE IF NOT EXISTS email_verification_tokens (


                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                           token VARCHAR(255) NOT NULL UNIQUE,

                                           user_id BIGINT NOT NULL,

                                           expiry_time TIMESTAMP NOT NULL,

                                           used BOOLEAN NOT NULL DEFAULT FALSE,

                                           created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                           CONSTRAINT fk_email_token_user
                                               FOREIGN KEY (user_id)
                                               REFERENCES users(user_id)
                                               ON DELETE CASCADE

);

CREATE INDEX idx_email_token_token
    ON email_verification_tokens(token);

CREATE INDEX idx_email_token_user
    ON email_verification_tokens(user_id);

-- ==========================================
-- PASSWORD RESET TOKENS
-- ==========================================

CREATE TABLE IF NOT EXISTS password_reset_tokens (

                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                       otp VARCHAR(255) NOT NULL,

                                       user_id BIGINT NOT NULL,

                                       expiry_time TIMESTAMP NOT NULL,

                                       used BOOLEAN NOT NULL DEFAULT FALSE,

                                       created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                       CONSTRAINT fk_password_reset_user
                                           FOREIGN KEY (user_id)
                                           REFERENCES users(user_id)
                                           ON DELETE CASCADE

);

CREATE INDEX idx_password_reset_user
    ON password_reset_tokens(user_id);

-- ==========================================
-- LOGIN AUDIT
-- ==========================================

CREATE TABLE IF NOT EXISTS login_audit (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             user_id BIGINT,

                             email VARCHAR(255),

                             login_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                             ip_address VARCHAR(100),

                             success BOOLEAN,

                             failure_reason VARCHAR(500),

                             CONSTRAINT fk_login_audit_user
                                 FOREIGN KEY (user_id)
                                 REFERENCES users(user_id)
                                 ON DELETE SET NULL

);

CREATE INDEX idx_login_audit_user
    ON login_audit(user_id);

CREATE INDEX idx_login_audit_email
    ON login_audit(email);
